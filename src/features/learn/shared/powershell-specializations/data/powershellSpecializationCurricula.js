Object.values(POWERSHELL_SPECIALIZATION_TRACKS).forEach((track) => {
  track.lessons = track.chapters.flatMap((chapter) => chapter.lessons);
  track.totalXp = track.lessons.reduce((sum, item) => sum + item.xp, 0);
});

export function getPowerShellSpecializationTrack(slug) {
  return POWERSHELL_SPECIALIZATION_TRACKS[slug] || null;
}
